    public function buildSchema($record) {

        $avroFieldSchema = [];

        $sub_field_count = [];

        foreach ($record as $field => $value) {

            $field = Helpers::cleanFieldName($field);

//            if (!array_key_exists($field, Config::$specialFields)) {

                $avroType = Config::$discoveredFieldOccurrence['foo_partition'][$field]['determined_type'];

                SkipprAvroSchemaConverter::buildAvroFields($avroFieldSchema, $field, $avroType, Config::$discoveredFieldOccurrence['foo_partition'], [], $sub_field_count);

//            }

        }

        return $avroFieldSchema;
    }

    public function assertParquetOutput($dir) {

        $foundFiles = false;

        array_map(function ($file) use (&$foundFiles) {

            $parquet = new \Parquet();
            $parquet->create_reader($file, 0);
            $info = $parquet->getInfo();
            $parquet->close_reader();

            // stdClass to array
            $info = json_decode(json_encode($info), true);
            
            $fileSchema = $info['schema']['schema'];

            $parCon = new AvroParquetSchemaConverter();
            $parquetSchema = $parCon->convert(Config::$avroSchema);

            foreach ($parquetSchema as $field => $attr) {

                $this->assertArrayHasKey($field, $fileSchema);

                if (key_exists('type', $fileSchema[$field])) { // @todo - recurse into nested
                    $this->assertEqualsIgnoringCase($fileSchema[$field]['type'], $parquetSchema[$field]['type']);
                }

                if (key_exists('optional', $fileSchema[$field])) { // @todo - recurse into nested
                    $this->assertEqualsIgnoringCase($fileSchema[$field]['optional'],
                        $parquetSchema[$field]['repeat']);
                }
            }

            $foundFiles = true;

        }, glob($dir));

        $this->assertTrue($foundFiles);

    }

    public function assertXmlOutput($dir) {

        $foundFiles = false;

        array_map(function ($file) use (&$foundFiles) {
            
            $content = file_get_contents($file);

            $serde = new SerderXml();
